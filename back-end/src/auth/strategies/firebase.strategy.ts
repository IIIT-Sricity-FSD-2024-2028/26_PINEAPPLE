import { Injectable, UnauthorizedException, ForbiddenException, Logger } from '@nestjs/common';
import { AuthStrategy, AuthUser } from './auth-strategy.interface';
import { FirebaseService } from '../../firebase/firebase.service';
import { UsersService } from '../../users/users.service';
import { normalizeRole } from '../../common/utils/role.util';
import { isProfileComplete } from '../../common/utils/profile.util';
import { buildSuspendedResponse } from '../../common/utils/suspended-response.util';
import { JwtStrategy } from './jwt.strategy';

@Injectable()
export class FirebaseStrategy implements AuthStrategy {
  readonly mode = 'firebase';
  private readonly logger = new Logger(FirebaseStrategy.name);
  private tokenCache = new Map<string, { decoded: any; timestamp: number }>();
  private readonly tokenTtlMs = 60000;

  constructor(
    private readonly firebaseService: FirebaseService,
    private readonly usersService: UsersService,
    private readonly jwtStrategy: JwtStrategy,
  ) {}

  resetToSeed(): void {
    this.tokenCache.clear();
  }

  async verify(request: any): Promise<AuthUser> {
    const authHeader = request.headers['authorization'] || request.headers['Authorization'];
    if (!authHeader || !String(authHeader).startsWith('Bearer ')) {
      throw new UnauthorizedException('Missing or invalid Authorization Bearer token.');
    }

    const token = String(authHeader).slice(7).trim();
    if (!token) {
      throw new UnauthorizedException('Empty Authorization token.');
    }

    // Fast-path: local HS256 tokens are HMAC-signed JWTs, not Google-issued RSA tokens
    try {
      const parts = token.split('.');
      if (parts.length === 3) {
        const header = JSON.parse(Buffer.from(parts[0], 'base64').toString('utf8'));
        if (header && header.alg === 'HS256') {
          return await this.jwtStrategy.verify(request);
        }
      }
    } catch (err: any) {
        console.warn('[firebase.strategy] Suppressed non-critical error:', err?.message || err);
      }

    try {
      let cached = this.tokenCache.get(token);
      if (!cached || Date.now() - cached.timestamp > this.tokenTtlMs) {
        const checkRevoked = !this.firebaseService.isEmulator();
        const freshDecoded = await this.firebaseService.auth.verifyIdToken(token, checkRevoked);
        cached = { decoded: freshDecoded, timestamp: Date.now() };
        this.tokenCache.set(token, cached);
        if (this.tokenCache.size > 2000) {
          const firstKey = this.tokenCache.keys().next().value;
          if (firstKey) this.tokenCache.delete(firstKey);
        }
      }
      const decoded = cached.decoded;

      const rawRole = (decoded.role as string) || (decoded.claims?.role as string) || 'Collaborator';
      const role = normalizeRole(rawRole);
      const permissions = (decoded.permissions as string[]) || (decoded.claims?.permissions as string[]) || [];

      // Phase 5: Check if user already exists in repository without deriving username from email
      const user =
        this.usersService.findRawUserById(decoded.uid) ||
        (decoded.email ? this.usersService.findRawUserByEmail(decoded.email) : null);

      if (user) {
        if ((user as any).isDeleted || (user as any).deletedAt) {
          throw new UnauthorizedException({
            statusCode: 401,
            error: 'Unauthorized',
            code: 'SESSION_INVALID',
            message: 'Account has been deleted.',
          });
        }
        const status = String(user.status || '').toLowerCase();
        if (status === 'suspended' || status === 'banned') {
          throw new ForbiddenException(buildSuspendedResponse(user));
        }
        const resolvedRole = normalizeRole(user.role || role);
        return {
          uid: String(user.id || decoded.uid),
          email: user.email || decoded.email,
          role: resolvedRole,
          permissions: resolvedRole === 'superuser' ? ['*'] : permissions,
          claims: decoded,
          name: user.name,
          username: user.username,
          profileComplete: isProfileComplete(user),
          usernameAutoGenerated: Boolean(user.usernameAutoGenerated),
          emailVerified: user.emailVerified !== false,
        };
      }

      // First-time social sign-in without a completed profile
      return {
        uid: decoded.uid,
        email: decoded.email,
        role: role,
        permissions: role === 'superuser' ? ['*'] : permissions,
        claims: decoded,
        name: decoded.name || '',
        username: '',
        profileComplete: false,
        usernameAutoGenerated: false,
        emailVerified: decoded.email_verified === true,
      };

      return {
        uid: decoded.uid,
        email: decoded.email,
        role,
        permissions: role === 'superuser' ? ['*'] : permissions,
        claims: decoded,
      };
    } catch (error: any) {
      if (error instanceof ForbiddenException) {
        throw error;
      }
      // Dual mode fallback: If token is a valid signed JWT, accept it
      try {
        return await this.jwtStrategy.verify(request);
      } catch (jwtErr: any) {
        if (jwtErr instanceof ForbiddenException) {
          throw jwtErr;
        }
        const errResp: any = typeof jwtErr?.getResponse === 'function' ? jwtErr.getResponse() : null;
        if (errResp?.code === 'SESSION_INVALID' || errResp?.code === 'TOKEN_EXPIRED') {
          throw jwtErr;
        }
        this.logger.warn(`Firebase token verification failed: ${error.message}`);
        throw new UnauthorizedException('Invalid or expired Firebase ID token.');
      }
    }
  }
}
