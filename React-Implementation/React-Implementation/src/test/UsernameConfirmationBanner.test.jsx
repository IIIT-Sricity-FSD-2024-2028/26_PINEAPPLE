import { describe, it, expect, vi, beforeEach } from 'vitest';
import { screen, waitFor, fireEvent } from '@testing-library/react';
import { render } from '@testing-library/react';
import UsernameConfirmationBanner from '../components/common/UsernameConfirmationBanner';
import { AuthContext } from '../context/AuthContext';
import { usersApi } from '../services/usersApi';

vi.mock('../services/usersApi', () => ({
  usersApi: {
    updateUsername: vi.fn(),
    checkUsernameAvailable: vi.fn(),
  },
  default: {
    updateUsername: vi.fn(),
    checkUsernameAvailable: vi.fn(),
  },
}));

function renderBanner(userOverrides = {}, authOverrides = {}) {
  const updateUser = vi.fn();
  const authValue = {
    user: {
      id: 'u-flagged',
      email: 'aditya@example.com',
      username: 'aditya',
      needsUsernameConfirmation: true,
      usernameAutoGenerated: true,
      ...userOverrides,
    },
    updateUser,
    ...authOverrides,
  };

  const utils = render(
    <AuthContext.Provider value={authValue}>
      <UsernameConfirmationBanner />
    </AuthContext.Provider>
  );

  return { ...utils, updateUser };
}

describe('Phase 5 - UsernameConfirmationBanner Component Tests', () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  it('does not render banner if user does not need confirmation', () => {
    renderBanner({ needsUsernameConfirmation: false });
    expect(screen.queryByRole('region', { name: /Username Confirmation/i })).toBeNull();
  });

  it('renders confirmation banner when user is flagged (needsUsernameConfirmation: true)', () => {
    renderBanner();

    expect(screen.getByRole('region', { name: /Username Confirmation/i })).toBeDefined();
    expect(screen.getByText('@aditya')).toBeDefined();
    expect(screen.getByRole('button', { name: /Got it/i })).toBeDefined();
  });

  it('calls usersApi.updateUsername with confirm: true when clicking Got it button', async () => {
    usersApi.updateUsername.mockResolvedValueOnce({
      success: true,
      username: 'aditya',
      needsUsernameConfirmation: false,
    });

    const { updateUser } = renderBanner();

    const gotItBtn = screen.getByRole('button', { name: /Got it/i });
    fireEvent.click(gotItBtn);

    await waitFor(() => {
      expect(usersApi.updateUsername).toHaveBeenCalledWith({ confirm: true });
      expect(updateUser).toHaveBeenCalledWith({
        needsUsernameConfirmation: false,
        usernameAutoGenerated: false,
      });
    });
  });

  it('renders locked username with note that username cannot be changed', () => {
    renderBanner();

    expect(screen.getByText(/Your username can't be changed/i)).toBeDefined();
    expect(screen.queryByPlaceholderText('new_username')).toBeNull();
  });
});
