export interface AuthUser {
  uid: string;
  email?: string;
  role: string;
  permissions?: string[];
  tokenVersion?: number;
  claims?: Record<string, any>;
  name?: string;
  username?: string;
  profileComplete?: boolean;
  usernameAutoGenerated?: boolean;
  emailVerified?: boolean;
}

export interface AuthStrategy {
  readonly mode: 'jwt' | 'firebase' | 'legacy';
  verify(request: any): Promise<AuthUser | null> | AuthUser | null;
}
