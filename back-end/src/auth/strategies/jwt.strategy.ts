import {
  Injectable,
  UnauthorizedException,
  ForbiddenException,
  Logger,
  Optional,
} from '@nestjs/common';
import { JwtService } from '@nestjs/jwt';
import { AuthStrategy, AuthUser } from './auth-strategy.interface';
import { UsersService } from '../../users/users.service';
import { PortalAdminsService } from '../../portal-admins/portal-admins.service';
import { BootService } from '../../system/boot.service';
import { normalizeRole } from '../../common/utils/role.util';
import { isProfileComplete } from '../../common/utils/profile.util';
import { buildSuspendedResponse } from '../../common/utils/suspended-response.util';

@Injectable()
export class JwtStrategy implements AuthStrategy {
  readonly mode = 'jwt';
  private readonly logger = new Logger(JwtStrategy.name);

  constructor(
    private readonly jwtService: JwtService,
    private readonly usersService: UsersService,
    @Optional() private readonly bootService?: BootService,
    @Optional() private readonly portalAdminsService?: PortalAdminsService,
  ) {}

  private getSecret(): string {
    return process.env.JWT_SECRET || 'teamforge-jwt-secret-key-development-minimum-32-chars';
  }

  async verify(request: any): Promise<AuthUser> {
    const authHeader = request.headers['authorization'] || request.headers['Authorization'];
    if (!authHeader || !String(authHeader).startsWith('Bearer ')) {
      throw new UnauthorizedException('Missing or invalid Authorization Bearer token.');
    }

    const token = String(authHeader).slice(7).trim();
    if (!token) {
      throw new UnauthorizedException('Empty Authorization token.');
    }

    let payload: any;
    try {
      payload = this.jwtService.verify(token, {
        secret: this.getSecret(),
        algorithms: ['HS256'],
        issuer: 'teamforge',
        audience: 'teamforge-web',
      });
    } catch (err: any) {
      this.logger.warn(`JWT verification failed: ${err.message}`);
      if (err?.name === 'TokenExpiredError' || String(err?.message || '').toLowerCase().includes('expired')) {
        throw new UnauthorizedException({
          statusCode: 401,
          error: 'Unauthorized',
          code: 'TOKEN_EXPIRED',
          message: 'Access token has expired.',
        });
      }
      throw new UnauthorizedException({
        statusCode: 401,
        error: 'Unauthorized',
        code: 'TOKEN_INVALID',
        message: 'Invalid access token.',
      });
    }

    if (!payload || !payload.sub) {
      throw new UnauthorizedException('Invalid token payload.');
    }

    // Step 2g: Server-side check - load user
    const user =
      this.usersService.findRawUserById(String(payload.sub)) ||
      (payload.email ? this.usersService.findRawUserByEmail(String(payload.email)) : null);

    // Policy check order: if user exists and is suspended, return ACCOUNT_SUSPENDED before any restart or session invalidation checks
    if (user) {
      const status = String(user.status || '').toLowerCase();
      if (status === 'suspended' || status === 'banned') {
        throw new ForbiddenException(buildSuspendedResponse(user));
      }
    }

    if (!user) {
      if (payload.profileComplete === false) {
        return {
          uid: String(payload.sub),
          email: payload.email,
          role: normalizeRole(payload.role || 'Collaborator'),
          permissions: [],
          tokenVersion: payload.tv,
          claims: payload,
          name: payload.name || '',
          username: '',
          profileComplete: false,
          usernameAutoGenerated: false,
        };
      }
      const resolvedRole = normalizeRole(payload.role);
      if (['admin', 'superuser'].includes(resolvedRole) && this.portalAdminsService) {
        const portalAdmins = this.portalAdminsService.findAll() || [];
        const portalAdmin = portalAdmins.find(
          (a: any) =>
            String(a.id) === String(payload.sub) ||
            (payload.email && String(a.email || '').toLowerCase() === String(payload.email).toLowerCase()),
        );
        if (portalAdmin) {
          const adminStatus = String(portalAdmin.status || 'active').toLowerCase();
          if (adminStatus === 'suspended' || adminStatus === 'disabled') {
            throw new ForbiddenException(buildSuspendedResponse(portalAdmin));
          }
          return {
            uid: String(portalAdmin.id || payload.sub),
            email: portalAdmin.email || payload.email,
            role: resolvedRole,
            permissions: resolvedRole === 'superuser' ? ['*'] : (portalAdmin.permissions || payload.permissions || ['dashboard']),
            tokenVersion: payload.tv,
            claims: payload,
            name: portalAdmin.name || payload.name || 'Admin',
            username: portalAdmin.email || payload.username || 'admin',
            profileComplete: true,
            usernameAutoGenerated: false,
          };
        }
      }
      throw new UnauthorizedException({
        statusCode: 401,
        error: 'Unauthorized',
        code: 'SESSION_INVALID',
        message: 'User no longer exists.',
      });
    }

    // Now check bootId (restart check) only after confirming user is not suspended
    if (this.bootService?.bootId) {
      if (!payload.bootId || payload.bootId !== this.bootService.bootId) {
        throw new UnauthorizedException({
          statusCode: 401,
          error: 'Unauthorized',
          code: 'SESSION_INVALID',
          message: 'Your session is no longer valid because the server restarted. Please log in again.',
        });
      }
    }

    // Reject if deleted
    if ((user as any).isDeleted || (user as any).deletedAt) {
      throw new UnauthorizedException({
        statusCode: 401,
        error: 'Unauthorized',
        code: 'SESSION_INVALID',
        message: 'Account has been deleted.',
      });
    }

    // Compare tv with user's tokenVersion (allow the single current jti retained across self email-change)
    if (user.tokenVersion !== undefined && payload.tv !== undefined) {
      if (payload.tv !== user.tokenVersion) {
        const isRetainedCallerSession =
          Boolean(payload.jti) &&
          Boolean((user as any).allowedLegacyJti) &&
          payload.jti === (user as any).allowedLegacyJti &&
          Number(payload.tv) === Number(user.tokenVersion) - 1;
        if (!isRetainedCallerSession) {
          throw new UnauthorizedException('Token has been revoked. Please log in again.');
        }
      }
    }

    const role = normalizeRole(user.role || payload.role || 'Collaborator');
    const permissions = role === 'superuser' ? ['*'] : (payload.permissions || []);

    return {
      uid: String(user.id || payload.sub),
      email: user.email || payload.email,
      role,
      permissions,
      tokenVersion: payload.tv,
      claims: payload,
      name: user.name,
      username: user.username,
      profileComplete: isProfileComplete(user),
      usernameAutoGenerated: Boolean(user.usernameAutoGenerated),
      emailVerified: user.emailVerified !== false,
    };
  }
}
