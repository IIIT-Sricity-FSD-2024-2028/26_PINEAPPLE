/**
 * Resends verification email (`POST /auth/resend-verification`).
 * If backend returns 409 EMAIL_ALREADY_VERIFIED, marks session verified automatically.
 */
export const resendEmailVerification = createAsyncThunk(
  'settings/resendEmailVerification',
  async (_arg, { dispatch, rejectWithValue }) => {
    try {
      const authApi = resolveApiForMethod(authApiModule, 'authApi', 'resendVerification');
      const res = await authApi.resendVerification();
      return {
        cooldownSeconds: Number(res?.cooldownSeconds) || 120,
        message: res?.message || 'Verification email sent. Please check your inbox.',
        alreadyVerified: false,
      };
    } catch (err) {
      const normalized = normalizeThunkError(err);
      if (
        normalized.code === 'EMAIL_ALREADY_VERIFIED' ||
        normalized.statusCode === 409
      ) {
        dispatch(userUpdated({ emailVerified: true }));
      }
      return rejectWithValue(normalized);
    }
  },
);

