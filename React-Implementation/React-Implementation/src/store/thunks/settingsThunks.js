/**
 * Verifies phone number with Firebase ID token (`POST /users/me/verify-phone`).
 */
export const verifyUserPhone = createAsyncThunk(
  'settings/verifyUserPhone',
  async ({ idToken, phoneE164 } = {}, { dispatch, rejectWithValue }) => {
    try {
      const usersApi = resolveApiForMethod(usersApiModule, 'usersApi', 'verifyPhone');
      const res = await usersApi.verifyPhone(idToken);
      const verifiedAt = res?.phoneVerifiedAt || new Date().toISOString();
      if (phoneE164) {
        dispatch(
          userUpdated({
            phone: phoneE164,
            phoneVerified: true,
            phoneVerifiedAt: verifiedAt,
            profile: {
              phone: phoneE164,
              phoneVerified: true,
              phoneVerifiedAt: verifiedAt,
            },
          }),
        );
      }
      return res || { phoneVerified: true, phoneVerifiedAt: verifiedAt };
    } catch (err) {
      return rejectWithValue(normalizeThunkError(err));
    }
  },
);

