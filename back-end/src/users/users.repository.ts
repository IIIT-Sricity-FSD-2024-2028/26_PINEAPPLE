  private indexUser(u: User): void {
    if (!u) return;
    this.usersById.set(String(u.id), u);
    if (u.isDeleted || u.deletedAt) {
      return;
    }
    if (u.email) {
      this.usersByEmail.set(u.email.trim().toLowerCase(), u);
    }
    const uname = (u.username || u.profile?.username || '').trim().toLowerCase();
    if (uname) {
      this.usersByUsername.set(uname, u);
    }
  }

  public rebuildIndexes(): void {
    this.usersById.clear();
    this.usersByEmail.clear();
    this.usersByUsername.clear();
    for (const u of this.users) {
      this.indexUser(u);
    }
  }

  public reindexUser(u?: User): void {
    this.rebuildIndexes();
  }

