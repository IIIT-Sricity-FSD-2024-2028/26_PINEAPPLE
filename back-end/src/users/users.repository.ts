  private detectAndFixDuplicates(): void {
    const seenNames = new Map<string, User>();
    const seenEmails = new Map<string, User>();
    const seenUsernames = new Map<string, User>();

    for (const user of this.users) {
      const cleanName = (user.name || '').replace(/\s*\([^)]*\)$/, '').trim().toLowerCase();
      const email = (user.email || '').trim().toLowerCase();
      const username = (user.username || user.profile?.username || '').trim().toLowerCase();

      // Check duplicates against real platform accounts (numeric IDs 1..9 are primary seed accounts)
      const isSeedDemoAccount = user.id.startsWith('u-');
      const isMatchingName = seenNames.has(cleanName);
      const isMatchingEmail = email && seenEmails.has(email);
      const isMatchingUsername = username && seenUsernames.has(username);

      if (isMatchingName || isMatchingEmail || isMatchingUsername) {
        const primary = seenNames.get(cleanName) || seenEmails.get(email) || seenUsernames.get(username)!;
        if (isSeedDemoAccount) {
          console.log(
            `[UsersRepository] Duplicate detected on start-up: Real record id '${primary.id}' ("${primary.name}", ${primary.email}) vs Seed record id '${user.id}' ("${user.name}", ${user.email}). Preserving real account id '${primary.id}' and marking seed record '${user.id}' as duplicate/hidden.`,
          );
          user.isDuplicate = true;
          user.isHidden = true;
          user.status = UserStatus.Inactive;
          continue;
        }
      }

      if (cleanName && !seenNames.has(cleanName)) {
        seenNames.set(cleanName, user);
      }
      if (email && !seenEmails.has(email)) {
        seenEmails.set(email, user);
      }
      if (username && !seenUsernames.has(username)) {
        seenUsernames.set(username, user);
      }
    }
    this.rebuildIndexes();
  }

