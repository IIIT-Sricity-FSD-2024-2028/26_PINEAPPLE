import { createAsyncThunk } from '@reduxjs/toolkit';
import * as usersApiModule from '../../services/usersApi';
import * as uploadsApiModule from '../../services/uploadsApi';
import * as authApiModule from '../../services/authApi';
import { resolveApiForMethod } from '../utils/apiModule';
import { normalizeThunkError } from '../utils/thunkError';
import { userUpdated } from '../slices/sessionSlice';

/**
 * Checks whether a username is available (`GET /users/username-available`).
 */
export const checkUsernameAvailability = createAsyncThunk(
  'settings/checkUsernameAvailability',
  async ({ username, excludeUserId } = {}, { rejectWithValue }) => {
    try {
      const usersApi = resolveApiForMethod(usersApiModule, 'usersApi', 'checkUsernameAvailable');
      const res = await usersApi.checkUsernameAvailable(username, excludeUserId);
      return res || { available: true };
    } catch (err) {
      return rejectWithValue(normalizeThunkError(err));
    }
  },
);

/**
 * Confirms an auto-generated username (`PATCH /users/me/username`) and syncs `sessionSlice`.
 */
export const confirmUsername = createAsyncThunk(
  'settings/confirmUsername',
  async (payload = { confirm: true }, { dispatch, rejectWithValue }) => {
    try {
      const usersApi = resolveApiForMethod(usersApiModule, 'usersApi', 'updateUsername');
      const res = await usersApi.updateUsername(payload);
      dispatch(
        userUpdated({
          needsUsernameConfirmation: false,
          usernameAutoGenerated: false,
          ...(res?.username ? { username: res.username } : {}),
        }),
      );
      return res || { success: true };
    } catch (err) {
      return rejectWithValue(normalizeThunkError(err));
    }
  },
);

/**
 * Uploads an avatar image (`POST /uploads/avatar`) and syncs `sessionSlice` immediately.
 */
export const uploadUserAvatar = createAsyncThunk(
  'settings/uploadUserAvatar',
  async (file, { dispatch, getState, rejectWithValue }) => {
    try {
      const uploadsApi = resolveApiForMethod(uploadsApiModule, 'uploadsApi', 'uploadAvatar');
      const res = await uploadsApi.uploadAvatar(file);
      const serverUser = res?.user && typeof res.user === 'object' ? res.user : null;
      const resolvedUrl =
        serverUser?.avatarUrl ||
        res?.avatarUrl ||
        res?.url ||
        (res?.filename ? `/uploads/${res.filename}` : null);
      const prevProfile = getState?.()?.session?.user?.profile || {};
      const updatedAt = serverUser?.updatedAt || new Date().toISOString();

      if (serverUser) {
        dispatch(
          userUpdated({
            ...serverUser,
            avatarUrl: resolvedUrl,
            avatar: resolvedUrl,
            updatedAt,
            profile: {
              ...prevProfile,
              ...(serverUser.profile || {}),
              avatarUrl: resolvedUrl,
              avatar: resolvedUrl,
            },
          }),
        );
      } else if (resolvedUrl) {
        dispatch(
          userUpdated({
            avatarUrl: resolvedUrl,
            avatar: resolvedUrl,
            updatedAt,
            profile: {
              ...prevProfile,
              avatarUrl: resolvedUrl,
              avatar: resolvedUrl,
            },
          }),
        );
      }

      return res || null;
    } catch (err) {
      return rejectWithValue(normalizeThunkError(err));
    }
  },
);

/**
 * Saves allow-listed user profile fields (`PATCH /users/:id`) and updates `sessionSlice`.
 */
export const saveProfileSettings = createAsyncThunk(
  'settings/saveProfileSettings',
  async ({ userId, payload, sessionPatch } = {}, { dispatch, rejectWithValue }) => {
    try {
      const usersApi = resolveApiForMethod(usersApiModule, 'usersApi', 'update');
      const uid = String(userId || '').trim();
      const updated = uid ? await usersApi.update(uid, payload) : null;
      const mergedSessionPatch = {
        ...(sessionPatch || {}),
        ...(updated && typeof updated === 'object' ? updated : {}),
      };
      if (Object.keys(mergedSessionPatch).length > 0) {
        dispatch(userUpdated(mergedSessionPatch));
      }
      return updated || mergedSessionPatch;
    } catch (err) {
      return rejectWithValue(normalizeThunkError(err));
    }
  },
);

