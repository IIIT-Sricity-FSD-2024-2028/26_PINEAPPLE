import {
  Controller,
  Post,
  Get,
  Body,
  Req,
  Res,
  Query,
  HttpCode,
  HttpStatus,
  UseGuards,
} from '@nestjs/common';
import { ApiTags, ApiOperation, ApiResponse, ApiBearerAuth } from '@nestjs/swagger';
import { AuthService } from './auth.service';
import { ForgotPasswordDto } from './dto/forgot-password.dto';
import { ResetPasswordDto } from './dto/reset-password.dto';
import { LoginDto } from './dto/login.dto';
import { SignupDto } from './dto/signup.dto';
import { RefreshTokenDto } from './dto/refresh.dto';
import { ChangePasswordDto } from './dto/change-password.dto';
import { SwitchRoleDto } from './dto/switch-role.dto';
import { CreateProfileDto } from './dto/create-profile.dto';
import { Public } from './decorators/public.decorator';
import { Roles } from '../core/decorators/roles.decorator';
import { CurrentUser } from './decorators/current-user.decorator';
import { AuthUser } from './strategies/auth-strategy.interface';
import { AuthGuard } from './guards/auth.guard';
import { stripUserSecrets } from '../users/user-serializer';

@ApiTags('Auth')
@Controller('auth')
export class AuthController {
  constructor(private readonly authService: AuthService) {}

  @Public()
  @Post('signup')
  @ApiOperation({ summary: 'Register a new user account' })
  @ApiResponse({ status: 201, description: 'User account created successfully.' })
  @ApiResponse({ status: 409, description: 'Username or email already exists.' })
  signup(
    @Body() dto: SignupDto,
    @Req() req: any,
    @Res({ passthrough: true }) res: any,
  ) {
    return this.authService.signup(dto, req, res);
  }

  @Public()
  @Post('login')
  @HttpCode(HttpStatus.OK)
  @ApiOperation({ summary: 'Log in with email/username and password' })
  @ApiResponse({ status: 200, description: 'Logged in successfully, returns tokens and profile.' })
  @ApiResponse({ status: 401, description: 'Invalid credentials.' })
  @ApiResponse({ status: 403, description: 'Account suspended.' })
  @ApiResponse({ status: 429, description: 'Too many failed login attempts.' })
  login(
    @Body() dto: LoginDto,
    @Req() req: any,
    @Res({ passthrough: true }) res: any,
  ) {
    const forwarded = req?.headers?.['x-forwarded-for'];
    const clientIp =
      (forwarded ? String(forwarded).split(',')[0].trim() : '') ||
      req?.ip ||
      req?.socket?.remoteAddress ||
      'unknown';
    return this.authService.login(dto, req, res, clientIp);
  }

  @Public()
  @Post('refresh')
  @HttpCode(HttpStatus.OK)
  @ApiOperation({ summary: 'Rotate refresh token and issue fresh access token' })
  @ApiResponse({ status: 200, description: 'Tokens rotated successfully.' })
  @ApiResponse({ status: 401, description: 'Invalid, expired, or reused refresh token.' })
  refresh(
    @Body() dto: RefreshTokenDto,
    @Req() req: any,
    @Res({ passthrough: true }) res: any,
  ) {
    return this.authService.refresh(dto?.refreshToken, req, res);
  }

  @Post('logout')
  @HttpCode(HttpStatus.OK)
  @ApiBearerAuth()
  @ApiOperation({ summary: 'Log out current session' })
  logout(
    @CurrentUser('uid') userId: string,
    @Body() dto: RefreshTokenDto,
    @Req() req: any,
    @Res({ passthrough: true }) res: any,
  ) {
    return this.authService.logout(userId, dto?.refreshToken, req, res);
  }

  @Post('logout-all')
  @HttpCode(HttpStatus.OK)
  @ApiBearerAuth()
  @ApiOperation({ summary: 'Revoke all active sessions and refresh tokens' })
  logoutAll(
    @CurrentUser('uid') userId: string,
    @Res({ passthrough: true }) res: any,
  ) {
    return this.authService.logoutAll(userId, res);
  }

  @Get('me')
  @ApiBearerAuth()
  @ApiOperation({ summary: 'Get current authenticated user profile and roles' })
  getMe(@CurrentUser() user: AuthUser) {
    const fullUser = user?.uid ? this.authService.getUserById(user.uid) : null;
    const mentorUnlocked = Boolean(
      (user as any)?.mentorUnlocked ||
      fullUser?.mentorUnlocked ||
      fullUser?.profile?.mentorUnlocked ||
      String(user?.role || '').toLowerCase() === 'mentor'
    );
    const profileComplete = (user as any)?.profileComplete !== undefined
      ? (user as any).profileComplete
      : (fullUser ? fullUser.profileComplete !== false : false);
    const needsUsernameConfirmation = Boolean(
      (user as any)?.usernameAutoGenerated ||
      fullUser?.usernameAutoGenerated
    );
    return stripUserSecrets({
      id: user?.uid,
      uid: user?.uid,
      email: user?.email,
      role: user?.role,
      permissions: user?.permissions,
      name: fullUser?.name || user?.name || '',
      username: fullUser?.username || user?.username || '',
      avatar: fullUser?.avatar || fullUser?.profile?.avatar || '',
      university: fullUser?.university || fullUser?.profile?.university || '',
      bio: fullUser?.profile?.bio || '',
      skills: fullUser?.skills || fullUser?.profile?.skills || [],
      profile: fullUser?.profile ? stripUserSecrets(fullUser.profile) : undefined,
      xp: fullUser?.xp,
      phone: fullUser?.phone,
      phoneVerified: Boolean(fullUser?.phoneVerified),
      mentorUnlocked,
      profileComplete,
      needsUsernameConfirmation,
      emailVerified: fullUser ? fullUser.emailVerified !== false : user?.emailVerified !== false,
      hasPassword: Boolean(fullUser?.password),
      claims: user?.claims,
    });
  }

  @Public()
  @Post('verify-email')
  @HttpCode(HttpStatus.OK)
  @ApiOperation({ summary: 'Verify email address using single-use 24-hour verification token' })
  @ApiResponse({ status: 200, description: 'Email verified successfully.' })
  @ApiResponse({ status: 400, description: 'Invalid, used, or expired verification token.' })
  verifyEmail(@Body() body: { token: string }) {
    return this.authService.verifyEmail(body?.token);
  }

  @Post('resend-verification')
  @HttpCode(HttpStatus.OK)
  @ApiBearerAuth()
  @ApiOperation({ summary: 'Resend email verification link (2-minute cooldown)' })
  @ApiResponse({ status: 200, description: 'Verification email sent.' })
  @ApiResponse({ status: 429, description: 'Cooldown active (RESEND_COOLDOWN).' })
  resendVerification(@CurrentUser() user: AuthUser) {
    return this.authService.resendVerificationEmail(user.uid);
  }

  @Post('change-password')
  @HttpCode(HttpStatus.OK)
  @ApiBearerAuth()
  @ApiOperation({ summary: 'Change password and revoke other active sessions' })
  changePassword(
    @CurrentUser('uid') userId: string,
    @Body() dto: ChangePasswordDto,
    @Res({ passthrough: true }) res: any,
  ) {
    return this.authService.changePassword(userId, dto, res);
  }

  @Post('switch-role')
  @HttpCode(HttpStatus.OK)
  @ApiBearerAuth()
  @ApiOperation({ summary: 'Switch current active role' })
  switchRole(
    @CurrentUser('uid') userId: string,
    @Body() dto: SwitchRoleDto,
    @Req() req: any,
    @Res({ passthrough: true }) res: any,
  ) {
    return this.authService.switchRole(userId, dto.role, req, res);
  }

  @Post('profile')
  @HttpCode(HttpStatus.OK)
  @ApiBearerAuth()
  @ApiOperation({ summary: 'Create or update profile on first sign in (Firebase/JWT)' })
  createProfile(
    @CurrentUser() user: AuthUser,
    @Body() dto: CreateProfileDto,
  ) {
    return this.authService.createOrUpdateProfile(user.uid, user.email, dto);
  }

  @Public()
  @Get('resolve-identifier')
  @ApiOperation({ summary: 'Resolve username to email for sign-in (rate-limited, safe)' })
  resolveIdentifier(@Query('identifier') identifier: string) {
    return this.authService.resolveIdentifier(identifier);
  }

  @Public()
  @Post('forgot-password')
  @HttpCode(HttpStatus.OK)
  @ApiOperation({ summary: 'Request a password reset link' })
  forgotPassword(@Body() dto: ForgotPasswordDto, @Req() req: any) {
    const clientIp = req.headers['x-forwarded-for']?.split(',')[0]?.trim() || req.ip || req.socket?.remoteAddress;
    return this.authService.forgotPassword(dto, clientIp);
  }

  @Public()
  @Post('reset-password')
  @HttpCode(HttpStatus.OK)
  @ApiOperation({ summary: 'Reset account password using reset token' })
  resetPassword(@Body() dto: ResetPasswordDto) {
    return this.authService.resetPassword(dto);
  }

  @Roles('superuser')
  @Post('test-set-expiry')
  @HttpCode(HttpStatus.OK)
  testSetExpiry(@Body() body: { expiryMs: number }) {
    if (body.expiryMs <= 0 || body.expiryMs === 15 * 60 * 1000) {
      this.authService.resetTokenExpiryMs();
      return { message: 'Expiry restored to default 15m' };
    }
    this.authService.setTokenExpiryMsForTest(body.expiryMs);
    return { message: `Expiry set to ${body.expiryMs}ms` };
  }
}
