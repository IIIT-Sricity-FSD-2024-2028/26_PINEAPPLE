import {
  IsEmail,
  IsString,
  IsOptional,
  IsArray,
  Length,
  Matches,
  ValidateIf,
} from 'class-validator';
import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

export enum UserRole {
  Collaborator = 'Collaborator',
  ProjectOwner = 'Project Owner',
  Mentor = 'Mentor',
  Administrator = 'Administrator',
  SuperUser = 'Super User',
}

export enum UserStatus {
  Active = 'Active',
  Suspended = 'Suspended',
  Warned = 'Warned',
  Flagged = 'Flagged',
  Banned = 'Banned',
  Inactive = 'Inactive',
}

/**
 * Public-safe CreateUserDto (no role, emailVerified, status, flags, or protected fields).
 */
export class CreateUserDto {
  @ApiProperty({ example: 'John Doe' })
  @IsString()
  name: string;

  @ApiProperty({ example: 'john.doe@example.com' })
  @IsEmail()
  email: string;

  @ApiPropertyOptional({ example: 'johndoe' })
  @IsString()
  @IsOptional()
  username?: string;

  @ApiPropertyOptional({ example: 'securePassword123' })
  @IsString()
  @IsOptional()
  password?: string;

  @ApiPropertyOptional({ type: [String], example: ['React', 'NestJS'] })
  @IsArray()
  @IsString({ each: true })
  @IsOptional()
  skills?: string[];

  @ApiPropertyOptional({ example: 'Passionate software engineer' })
  @IsString()
  @IsOptional()
  bio?: string;

  @ApiPropertyOptional({ example: 'Carnegie Mellon University' })
  @IsString()
  @IsOptional()
  @ValidateIf((o) => typeof o.university === 'string' && o.university.trim() !== '')
  @Length(2, 100, { message: 'University must be between 2 and 100 characters' })
  @Matches(/^[a-zA-Z0-9\s.,&\-'()]+$/, {
    message:
      "University contains invalid characters. Use letters, numbers, spaces, and common punctuation (. , & - ' ( ))",
  })
  university?: string;

  @ApiPropertyOptional({ example: 'https://linkedin.com/in/johndoe' })
  @IsString()
  @IsOptional()
  linkedIn?: string;
}

/**
 * Internal-only payload for trusted backend services (e.g., AuthService.signup, seeding, tests).
 */
export interface InternalCreateUserInput {
  name: string;
  email: string;
  username?: string;
  password?: string;
  role?: UserRole;
  status?: UserStatus;
  emailVerified?: boolean;
  emailVerifiedAt?: string;
  flags?: boolean;
  skills?: string[];
  bio?: string;
  university?: string;
  linkedIn?: string;
  phone?: string;
  phoneVerified?: boolean;
  phoneVerifiedAt?: string;
  avatar?: string;
  links?: Record<string, any>;
  profileComplete?: boolean;
  usernameAutoGenerated?: boolean;
  profile?: Record<string, any>;
}
