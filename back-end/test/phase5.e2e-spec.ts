import { INestApplication } from '@nestjs/common';
import request from 'supertest';
import * as fs from 'fs';
import * as path from 'path';
import { createTestApp, TestAppContext } from './helpers/test-helpers';

describe('Phase 5 E2E Tests: Username Enforcement, Profile Completion, Confirmation & Zero Derivation', () => {
  let ctx: TestAppContext;
  let app: INestApplication;
  let server: any;

  beforeAll(async () => {
    ctx = await createTestApp();
    app = ctx.app;
    server = app.getHttpServer();
  });

  beforeEach(() => {
    ctx.resetStores();
  });

  afterAll(async () => {
    await app.close();
  });

  describe('1. Two-Step Signup Without Username', () => {
    it('signup succeeds with email + password only, leaves username empty & profileComplete false, and requires step 2', async () => {
      const res = await request(server)
        .post('/auth/signup')
        .send({
          email: 'jane.smith@example.com',
          password: 'Password@123',
          role: 'Collaborator',
        });

      expect(res.status).toBe(201);
      expect(res.body.user).toBeDefined();
      expect(res.body.user.username).toBe('');
      expect(res.body.user.email).toBe('jane.smith@example.com');
      expect(res.body.user.name).toBe('jane.smith');
      expect(res.body.user.profileComplete).toBe(false);
      expect(res.body.user.usernameAutoGenerated).toBe(false);

      const signupToken = `Bearer ${res.body.accessToken}`;

      // Verify user lookup shows incomplete profile & no username
      const meRes = await request(server)
        .get('/users/me')
        .set('Authorization', signupToken);

      expect(meRes.status).toBe(200);
      expect(meRes.body.username).toBe('');
      expect(meRes.body.profileComplete).toBe(false);

      // Incomplete user is blocked on protected routes and hidden from search & leaderboard
      const projBlocked = await request(server)
        .get('/projects')
        .set('Authorization', signupToken);
      expect(projBlocked.status).toBe(403);
      expect(projBlocked.body.code).toBe('PROFILE_INCOMPLETE');

      const searchBefore = await request(server)
        .get('/users/search?q=jane.smith')
        .set('Authorization', ctx.loginAs('1'));
      expect(searchBefore.status).toBe(200);
      expect(searchBefore.body.some((u: any) => String(u.id) === String(res.body.user.id))).toBe(false);

      const lbBefore = await request(server)
        .get('/leaderboard')
        .set('Authorization', ctx.loginAs('1'));
      expect(lbBefore.status).toBe(200);
      expect(lbBefore.body.some((e: any) => String(e.userId) === String(res.body.user.id))).toBe(false);

      // Step 2: taken username fails at /auth/profile, unused username succeeds and unlocks everything
      const takenRes = await request(server)
        .post('/auth/profile')
        .set('Authorization', signupToken)
        .send({ name: 'Jane Doe', username: 'priyapatel' });
      expect(takenRes.status).toBe(409);
      expect(takenRes.body.code).toBe('USERNAME_TAKEN');

      const completeRes = await request(server)
        .post('/auth/profile')
        .set('Authorization', signupToken)
        .send({ name: 'Jane Doe', username: 'custom_coder_42', university: 'IIT Bombay' });
      expect(completeRes.status).toBe(200);
      expect(completeRes.body.username).toBe('custom_coder_42');
      expect(completeRes.body.profileComplete).toBe(true);
      expect(completeRes.body.needsUsernameConfirmation).toBe(false);

      // Now appears in user search & leaderboard
      const searchAfter = await request(server)
        .get('/users/search?q=custom_coder_42')
        .set('Authorization', ctx.loginAs('1'));
      expect(searchAfter.status).toBe(200);
      expect(searchAfter.body.some((u: any) => u.username === 'custom_coder_42')).toBe(true);

      const lbAfter = await request(server)
        .get('/leaderboard')
        .set('Authorization', ctx.loginAs('1'));
      expect(lbAfter.status).toBe(200);
      expect(lbAfter.body.some((e: any) => String(e.userId) === String(res.body.user.id))).toBe(true);
    });

    it('ignores any username field sent directly to POST /auth/signup', async () => {
      const res = await request(server)
        .post('/auth/signup')
        .send({
          name: 'Ignored Username User',
          email: 'ignored.uname@example.com',
          username: 'priyapatel', // even an existing username is ignored on signup
          password: 'Password@123',
          role: 'Collaborator',
        });

      expect(res.status).toBe(201);
      expect(res.body.user.username).toBe('');
      expect(res.body.user.profileComplete).toBe(false);
    });
  });

  describe('2. Incomplete Profile Enforcement (HTTP 403 PROFILE_INCOMPLETE)', () => {
    it('returns 403 PROFILE_INCOMPLETE when user has profileComplete: false on protected routes', async () => {
      // Create a token for a new social user with profileComplete: false
      const socialToken = ctx.loginAs(
        'social-new-user-1',
        undefined,
        {
          profileComplete: false,
          email: 'social.coder@gmail.com',
          name: 'Social Coder',
        },
      );

      // Attempt to access protected resources
      const projRes = await request(server)
        .get('/projects')
        .set('Authorization', socialToken);

      expect(projRes.status).toBe(403);
      expect(projRes.body.code).toBe('PROFILE_INCOMPLETE');
      expect(projRes.body.message).toContain('complete your profile');

      // Attempt to access notifications
      const notifRes = await request(server)
        .get('/notifications')
        .set('Authorization', socialToken);

      expect(notifRes.status).toBe(403);
      expect(notifRes.body.code).toBe('PROFILE_INCOMPLETE');

      // Attempt to create a task
      const postTaskRes = await request(server)
        .post('/tasks')
        .set('Authorization', socialToken)
        .send({ title: 'Task Under Incomplete Profile', projectId: 'proj-1' });

      expect(postTaskRes.status).toBe(403);
      expect(postTaskRes.body.code).toBe('PROFILE_INCOMPLETE');
    });

    it('allows access to whitelisted endpoints while profileComplete is false', async () => {
      const socialToken = ctx.loginAs(
        'social-new-user-2',
        undefined,
        {
          profileComplete: false,
          email: 'social.two@gmail.com',
          name: 'Social Two',
        },
      );

      // 1. GET /users/me succeeds
      const meRes = await request(server)
        .get('/users/me')
        .set('Authorization', socialToken);

      expect(meRes.status).toBe(200);
      expect(meRes.body.profileComplete).toBe(false);
      expect(meRes.body.email).toBe('social.two@gmail.com');

      // 2. GET /auth/me succeeds
      const authMeRes = await request(server)
        .get('/auth/me')
        .set('Authorization', socialToken);

      expect(authMeRes.status).toBe(200);
      expect(authMeRes.body.profileComplete).toBe(false);

      // 3. GET /users/username-available succeeds
      const availRes = await request(server)
        .get('/users/username-available?username=fresh_handle_99')
        .set('Authorization', socialToken);

      expect(availRes.status).toBe(200);
      expect(availRes.body.available).toBe(true);

      // 4. POST /auth/logout succeeds
      const logoutRes = await request(server)
        .post('/auth/logout')
        .set('Authorization', socialToken)
        .send({});

      expect(logoutRes.status).toBe(200);
    });
  });

  describe('3. Social Profile Creation & Validation (POST /auth/profile)', () => {
    it('returns 400 USERNAME_REQUIRED if username is omitted when completing profile', async () => {
      const socialToken = ctx.loginAs(
        'social-user-no-username',
        undefined,
        {
          profileComplete: false,
          email: 'noname@gmail.com',
          name: 'No Name Coder',
        },
      );

      const res = await request(server)
        .post('/auth/profile')
        .set('Authorization', socialToken)
        .send({
          name: 'No Name Coder',
          username: '',
        });

      expect(res.status).toBe(400);
      expect(res.body.code).toBe('USERNAME_REQUIRED');
    });

    it('returns 409 USERNAME_TAKEN if chosen username is already claimed', async () => {
      const socialToken = ctx.loginAs(
        'social-user-dup',
        undefined,
        {
          profileComplete: false,
          email: 'dup@gmail.com',
          name: 'Dup Coder',
        },
      );

      // Priya Patel has username 'priyapatel'
      const res = await request(server)
        .post('/auth/profile')
        .set('Authorization', socialToken)
        .send({
          name: 'Dup Coder',
          username: 'PriyaPatel', // case-insensitive check
        });

      expect(res.status).toBe(409);
      expect(res.body.code).toBe('USERNAME_TAKEN');
    });

    it('successfully completes profile and unlocks protected routes', async () => {
      const socialToken = ctx.loginAs(
        'social-user-valid',
        undefined,
        {
          profileComplete: false,
          email: 'social.coder@gmail.com',
          name: 'Social Coder',
        },
      );

      const res = await request(server)
        .post('/auth/profile')
        .set('Authorization', socialToken)
        .send({
          name: 'Social Coder',
          username: 'social_coder_101',
          university: 'BITS Pilani',
        });

      expect(res.status).toBe(200);
      expect(res.body.username).toBe('social_coder_101');
      expect(res.body.profileComplete).toBe(true);
      expect(res.body.needsUsernameConfirmation).toBe(false);

      // Now protected routes are unlocked!
      const projRes = await request(server)
        .get('/projects')
        .set('Authorization', socialToken);

      expect(projRes.status).toBe(200);
    });
  });

  describe('4. Flagged Existing Accounts & Username Confirmation Banner Flow', () => {
    it('returns needsUsernameConfirmation: true for flagged account u-collab', async () => {
      const collabToken = ctx.loginAs('u-collab');

      const meRes = await request(server)
        .get('/users/me')
        .set('Authorization', collabToken);

      expect(meRes.status).toBe(200);
      expect(meRes.body.username).toBe('aditya');
      expect(meRes.body.email).toBe('aditya@example.com');
      expect(meRes.body.needsUsernameConfirmation).toBe(true);
      expect(meRes.body.profileComplete).toBe(true);
    });

    it('clears confirmation flag when PATCH /users/me/username is called with confirm: true', async () => {
      const collabToken = ctx.loginAs('u-collab');

      const patchRes = await request(server)
        .patch('/users/me/username')
        .set('Authorization', collabToken)
        .send({ confirm: true });

      expect(patchRes.status).toBe(200);
      expect(patchRes.body.needsUsernameConfirmation).toBe(false);
      expect(patchRes.body.username).toBe('aditya');

      // Subsequent GET /users/me reflects cleared flag
      const meRes = await request(server)
        .get('/users/me')
        .set('Authorization', collabToken);

      expect(meRes.status).toBe(200);
      expect(meRes.body.needsUsernameConfirmation).toBe(false);
    });

    it('rejects changing an existing chosen username with 400 USERNAME_IMMUTABLE', async () => {
      const ownerToken = ctx.loginAs('1');

      const patchRes = await request(server)
        .patch('/users/me/username')
        .set('Authorization', ownerToken)
        .send({ username: 'priya_new' });

      expect(patchRes.status).toBe(400);
      expect(patchRes.body.code).toBe('USERNAME_IMMUTABLE');
    });
  });

  describe('5. Source Code Derivation Audit', () => {
    it('asserts zero occurrences of username derivation from email across back-end/src', () => {
      const srcDir = path.resolve(process.cwd(), 'src');

      function getAllFiles(dirPath: string, arrayOfFiles: string[] = []): string[] {
        const files = fs.readdirSync(dirPath);
        for (const file of files) {
          const fullPath = path.join(dirPath, file);
          if (fs.statSync(fullPath).isDirectory()) {
            getAllFiles(fullPath, arrayOfFiles);
          } else if (file.endsWith('.ts')) {
            arrayOfFiles.push(fullPath);
          }
        }
        return arrayOfFiles;
      }

      const allFiles = getAllFiles(srcDir);
      const violations: string[] = [];

      // Regex patterns that would indicate deriving or fallback-building username from email
      // e.g., username = email.split('@')[0], username || email.split, cleanUsername = ... email.split
      const illegalDerivationRegex = /(username\s*[:=]\s*[^;\n]*email\.split|username\s*\|\|\s*[^;\n]*email\.split|cleanUsername\s*[:=]\s*[^;\n]*email\.split)/i;

      for (const filePath of allFiles) {
        const content = fs.readFileSync(filePath, 'utf8');
        const lines = content.split('\n');
        lines.forEach((line, lineNum) => {
          if (illegalDerivationRegex.test(line)) {
            // Exceptions: only allowed if it is a boolean equality check (=== or !==) for flagging
            const isFlagCheck = line.includes('===') || line.includes('!==');
            if (!isFlagCheck) {
              violations.push(`${path.relative(srcDir, filePath)}:${lineNum + 1}: ${line.trim()}`);
            }
          }
        });
      }

      expect(violations).toEqual([]);
    });
  });
});
